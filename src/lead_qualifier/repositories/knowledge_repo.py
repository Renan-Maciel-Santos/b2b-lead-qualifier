"""Knowledge base vector persistence and retrieval using PostgreSQL pgvector."""

import json
from typing import Any

from psycopg import AsyncConnection
from psycopg.rows import dict_row


class KnowledgeRepository:
    """Repository managing vector embeddings and semantic search for RAG."""

    def __init__(self, conn: AsyncConnection) -> None:
        """Initialize repository with a tenant-scoped database connection.

        Args:
            conn: PostgreSQL async connection with tenant RLS active.
        """
        self.conn = conn

    async def search_similar_chunks(
        self,
        embedding: list[float],
        limit: int = 3,
        embedding_model: str | None = None,
    ) -> list[dict[str, Any]]:
        """Find most similar text chunks using cosine distance over vector embeddings.

        Args:
            embedding: Query embedding vector.
            limit: Maximum number of relevant chunks to retrieve.
            embedding_model: Optional filter to isolate embeddings generated by the same model.

        Returns:
            list[dict[str, Any]]: Ranked list of chunks with title, content, metadata, and similarity.
        """
        embedding_str = f"[{','.join(map(str, embedding))}]"

        async with self.conn.cursor(row_factory=dict_row) as cur:
            if embedding_model:
                await cur.execute(
                    """
                    SELECT title, content, metadata, 1 - (embedding <=> %s::public.vector) AS similarity
                    FROM knowledge_base
                    WHERE embedding_model = %s
                    ORDER BY embedding <=> %s::public.vector
                    LIMIT %s
                    """,
                    (embedding_str, embedding_model, embedding_str, limit),
                )
            else:
                await cur.execute(
                    """
                    SELECT title, content, metadata, 1 - (embedding <=> %s::public.vector) AS similarity
                    FROM knowledge_base
                    ORDER BY embedding <=> %s::public.vector
                    LIMIT %s
                    """,
                    (embedding_str, embedding_str, limit),
                )
            return await cur.fetchall()

    async def insert_chunk(
        self,
        title: str,
        content: str,
        embedding: list[float],
        embedding_model: str = "text-embedding-3-small",
        metadata: dict[str, Any] | None = None,
    ) -> None:
        """Insert or update a vectorized chunk into the tenant's knowledge base.

        Uses content hash deduplication to ensure idempotency.

        Args:
            title: Document or chunk title.
            content: Raw textual content of the chunk.
            embedding: Precomputed vector embedding.
            embedding_model: Identifier of the embedding model used.
            metadata: Additional document metadata (e.g. source, page number).
        """
        embedding_str = f"[{','.join(map(str, embedding))}]"
        meta_json = json.dumps(metadata or {})

        async with self.conn.cursor() as cur:
            await cur.execute(
                """
                INSERT INTO knowledge_base (
                    title, content, embedding, embedding_model, metadata
                ) VALUES (%s, %s, %s::public.vector, %s, %s)
                ON CONFLICT (tenant_id, content_hash) DO UPDATE
                SET title = EXCLUDED.title,
                    metadata = EXCLUDED.metadata,
                    updated_at = now()
                """,
                (title, content, embedding_str, embedding_model, meta_json),
            )
